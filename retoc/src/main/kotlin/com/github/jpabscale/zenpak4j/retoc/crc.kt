private fun String.to_ascii_uppercase(): String {
    val sb = StringBuilder(this.length)
    for (ch in this) {
        if (ch in 'a'..'z') sb.append((ch.code - 32).toChar())
        else sb.append(ch)
    }
    return sb.toString()
}

private fun String.encode_utf16(): List<UShort> {
    // Rust: str::encode_utf16 collects u16 code units (including surrogates)
    // Kotlin String is UTF-16; iterate Char (code units) directly for parity.
    // For BMP, ch.code fits u16; for supplementary, Kotlin already stores surrogate pair as two Chars.
    val list = ArrayList<UShort>(this.length)
    for (ch in this) {
        list.add(ch.code.toUShort())
    }
    return list
}
