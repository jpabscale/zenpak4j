// Rust: retoc/src/crc.rs:61 calc_crc
fun calc_crc(data: ByteArray): UInt {
    var crc: UInt = 0xFFFFFFFFu
    for (b in data) {
        crc = (crc shr 8) xor CRC_TABLE[((crc and 0xFFu) xor b.toUByte().toUInt()).toInt()]
    }
    // Rust: (!crc).swap_bytes()
    return java.lang.Integer.reverseBytes(crc.inv().toInt()).toUInt()
}

